/* =====================================================================
   DO NOT EDIT THIS FILE.
   This code reads everything from  js/content.js  and builds the pages.
   To change text, contact details, projects or pictures, edit content.js.

   What is inside (in order):
     1. Small helper functions
     2. Text, lists and cards for each page
     3. Pictures (profile, covers, project images)
     4. Page switching and the mobile menu
     5. Extras (greeting, live clock, copy buttons)
   ===================================================================== */

(function () {
  "use strict";

  var S = SITE; // everything you wrote in content.js


  /* ===================================================================
     1. SMALL HELPERS
     =================================================================== */

  // Read a value from content.js by its path, for example "home.intro"
  function get(path) {
    return path.split(".").reduce(function (obj, key) {
      return obj == null ? undefined : obj[key];
    }, S);
  }

  // Make text safe to place inside HTML
  function esc(text) {
    return String(text == null ? "" : text).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  // Build a small icon from the icon library in index.html
  function icon(name, size) {
    return '<svg class="icon' + (size ? " icon-" + size : "") + '" aria-hidden="true"><use href="#i-' + esc(name) + '"></use></svg>';
  }

  // Build the HTML for every item of a list
  function each(list, makeHtml) {
    return (list || []).map(makeHtml).join("");
  }

  // Put HTML into the element with the given id
  function put(id, html) {
    var el = document.getElementById(id);
    if (el) el.innerHTML = html;
  }

  // Build a row of small tags, for example: Gmail  Google Calendar
  function chips(list, extraClass) {
    return each(list, function (t) {
      return '<span class="chip ' + (extraClass || "") + '">' + esc(t) + "</span>";
    });
  }

  // Try to load a picture. Calls onFound only if the file really exists.
  function tryImage(path, onFound) {
    if (!path) return;
    var img = new Image();
    img.onload = function () { onFound(encodeURI(path)); };
    img.src = encodeURI(path);
  }


  /* ===================================================================
     2. TEXT, LISTS AND CARDS
     =================================================================== */

  // 2a. Plain text: any element with data-text="..." in index.html
  function fillTexts() {
    document.querySelectorAll("[data-text]").forEach(function (el) {
      var value = get(el.getAttribute("data-text"));
      if (value === undefined || value === "") {
        el.hidden = true;               // hide empty text such as an unused subtitle
      } else {
        el.textContent = value;
      }
    });
  }

  // 2b. Home page
  function buildHome() {
    var h = S.home;

    put("homeFacts", each(h.quickFacts, function (f) {
      return "<li>" + icon(f.icon) + "<span>" + esc(f.text) + "</span></li>";
    }));

    put("whyGrid", each(h.why, function (c) {
      return '<div class="col-12 col-md-6 col-lg-3"><div class="tile">' +
        '<div class="tile-icon">' + icon(c.icon, "lg") + "</div>" +
        "<h3>" + esc(c.title) + "</h3><p>" + esc(c.text) + "</p></div></div>";
    }));

    put("toolGrid", each(h.tools, function (t) {
      return '<div class="col"><div class="tool"><div class="tool-art">' + icon(t.icon, "lg") + "</div>" +
        '<div class="tool-text"><div class="tool-name">' + esc(t.name) + '</div><div class="tool-sub">' + esc(t.detail) + "</div></div></div></div>";
    }));

    put("nicheList", each(h.niche, function (n) {
      return '<div class="niche">' + icon(n.icon, "lg") +
        "<div><h3>" + esc(n.title) + "</h3><p>" + esc(n.text) + "</p></div></div>";
    }));

    put("featuredGrid", each(S.projects.items.slice(0, h.featuredCount), function (p) {
      return '<div class="col-12 col-md-6 col-lg-4"><a class="ftile" href="#projects" data-page="projects">' +
        '<div class="ftile-art" data-image="' + esc(p.image) + '">' + icon(p.icon, "xl") +
        '<span class="play" aria-hidden="true">' + icon("arrow-right", "lg") + "</span></div>" +
        "<h3>" + esc(p.title) + "</h3><p>" + esc(p.tools.join(", ")) + "</p></a></div>";
    }));

    put("readyGrid", each(h.ready, function (r) {
      return '<div class="col-12 col-sm-6 col-lg-3"><div class="ready-item">' +
        '<div class="eyebrow">' + icon(r.icon) + esc(r.label) + "</div><p>" + esc(r.text) + "</p></div></div>";
    }));
  }

  // 2c. About page
  function buildAbout() {
    var a = S.about;

    put("aboutProse", each(a.paragraphs, function (text, i) {
      return '<p class="' + (i === 0 ? "lead" : "") + '">' + esc(text) + "</p>";
    }));

    put("aboutFacts", each(a.facts, function (f) {
      return '<div class="fact"><p class="eyebrow">' + esc(f.label) + "</p><p>" + esc(f.value) + "</p></div>";
    }));

    put("principleGrid", each(a.principles, function (p) {
      return '<div class="col-12 col-md-6"><div class="tile principle">' +
        '<div class="tile-icon">' + icon(p.icon, "lg") + "</div>" +
        "<div><h3>" + esc(p.title) + "</h3><p>" + esc(p.text) + "</p></div></div></div>";
    }));

    put("strengthChips", chips(a.strengths, "green"));

    put("serviceGrid", each(a.services, function (s) {
      return '<div class="col-12 col-md-6 col-lg-4"><div class="tile">' +
        '<div class="tile-icon">' + icon(s.icon, "lg") + "</div>" +
        "<h3>" + esc(s.title) + "</h3><p>" + esc(s.text) + "</p></div></div>";
    }));
  }

  // 2d. Projects page (every card has the same size)
  function buildProjects() {
    var items = S.projects.items;

    // Filter buttons: "All" plus every category found in your projects
    var categories = ["All"];
    items.forEach(function (p) {
      if (categories.indexOf(p.category) < 0) categories.push(p.category);
    });
    put("filters", each(categories, function (c, i) {
      return '<button type="button" class="filter' + (i === 0 ? " active" : "") + '" data-filter="' + esc(c) + '">' + esc(c) + "</button>";
    }));

    // Cards
    put("projectGrid", each(items, function (p) {
      var link = p.link
        ? '<a class="btn-pill btn-ghost btn-small" href="' + esc(p.link) + '" target="_blank" rel="noopener">View project ' + icon("arrow-right") + "</a>"
        : "";
      return '<article class="pcard" data-category="' + esc(p.category) + '">' +
        '<div class="pmedia" data-image="' + esc(p.image) + '" style="--fit:' + esc(p.fit || "contain") + ";--focus:" + esc(p.focus || "center") + '">' +
          '<div class="pph">' + icon(p.icon, "xl") + "</div>" +
        "</div>" +
        '<div class="pbody">' +
          (S.projects.badge ? '<span class="ptag">' + esc(S.projects.badge) + "</span>" : "") +
          "<h3>" + esc(p.title) + "</h3>" +
          "<p>" + esc(p.caption) + "</p>" +
          '<div class="pfoot"><p class="tools-label">Tools used</p><div class="chips">' + chips(p.tools, "green") + "</div>" + link + "</div>" +
        "</div></article>";
    }));
  }

  // 2e. Resume page
  function groupBlock(g) {
    return '<div class="skill-group"><p class="tools-label">' + esc(g.group) + '</p><div class="chips">' +
      chips(g.items, g.highlight ? "green" : "") + "</div></div>";
  }

  function buildResume() {
    var r = S.resume;

    put("jobList", each(r.experience, function (j) {
      return '<article class="job"><div class="job-top"><h3>' + esc(j.title) + '</h3><span class="job-date">' + esc(j.dates) + "</span></div>" +
        '<p class="job-org">' + esc(j.company) + "</p>" +
        "<ul>" + each(j.bullets, function (b) { return "<li>" + esc(b) + "</li>"; }) + "</ul></article>";
    }));

    put("eduList", each(r.education, function (e) {
      return '<article class="job"><div class="job-top"><h3>' + esc(e.title) + '</h3><span class="job-date">' + esc(e.dates) + "</span></div>" +
        '<p class="job-org no-gap">' + esc(e.school) + "</p></article>";
    }));

    put("skillGroups", each(r.skills, groupBlock));
    put("techGroups", each(r.tech, groupBlock));

    put("remoteList", each(r.remote, function (x) {
      return "<li>" + icon(x.icon) + "<span>" + esc(x.text) + "</span></li>";
    }));

    put("languageList", each(r.languages, function (l) {
      return "<li>" + icon("globe") + "<span>" + esc(l) + "</span></li>";
    }));
  }

  // 2f. Contact page
  function buildContact() {
    document.getElementById("emailLink").href = "https://mail.google.com/mail/?view=cm&fs=1&to=" + S.email;
    document.getElementById("emailLink").target = "_blank";
    document.getElementById("phoneLink").href = "tel:" + S.phoneLink;

    put("stepList", each(S.contact.steps, function (s, i) {
      return '<div class="step"><span class="step-n">' + (i + 1) + "</span>" +
        "<div><h3>" + esc(s.title) + "</h3><p>" + esc(s.text) + "</p></div></div>";
    }));
  }


  /* ===================================================================
     3. PICTURES
     If a picture file is missing, the placeholder or cover art stays.
     =================================================================== */

  // Profile picture
  function loadProfilePicture() {
    tryImage(S.images.profile, function (url) {
      var img = document.getElementById("avatarImg");
      img.src = url;
      img.alt = "Portrait of " + S.name;
      img.hidden = false;
      document.getElementById("avatar").classList.add("has-photo");
    });
  }

  // Cover picture at the top of each page
  function loadCovers() {
    document.querySelectorAll("[data-cover]").forEach(function (cover) {
      var path = S.images.covers[cover.getAttribute("data-cover")];
      tryImage(path, function (url) {
        cover.querySelector(".cover-photo").style.backgroundImage = 'url("' + url + '")';
        cover.classList.add("has-photo");
      });
    });
  }

  // Project pictures (Projects page) and small pictures (Featured projects on Home)
  function loadProjectPictures() {
    document.querySelectorAll("[data-image]").forEach(function (box) {
      tryImage(box.getAttribute("data-image"), function (url) {
        var img = document.createElement("img");
        img.src = url;
        img.alt = "";
        box.appendChild(img);
        // A full address is needed here, because this value is read from inside style.css
        box.style.setProperty("--img", 'url("' + new URL(url, document.baseURI).href + '")');
        box.classList.add("has-image");
      });
    });
  }


  /* ===================================================================
     4. PAGE SWITCHING AND MOBILE MENU
     =================================================================== */

  var PAGES = ["home", "about", "projects", "resume", "contact"];
  var navLinks = document.querySelectorAll(".nav-pill");
  var navMenu = document.getElementById("navmenu");
  var navButton = document.getElementById("navToggle");

  function showPage(name, scrollToTop) {
    if (PAGES.indexOf(name) < 0) name = "home";

    document.querySelectorAll(".page").forEach(function (page) {
      page.hidden = page.getAttribute("data-page") !== name;
    });

    navLinks.forEach(function (link) {
      var active = link.getAttribute("data-page") === name;
      link.classList.toggle("active", active);
      if (active) link.setAttribute("aria-current", "page");
      else link.removeAttribute("aria-current");
    });

    if (scrollToTop !== false) window.scrollTo(0, 0);
    navMenu.classList.remove("show");
    navButton.setAttribute("aria-expanded", "false");
  }

  // Clicking any link with data-page="..." switches the page
  document.addEventListener("click", function (e) {
    var link = e.target.closest("a[data-page]");
    if (!link) return;
    e.preventDefault();
    var name = link.getAttribute("data-page");
    showPage(name);
    try { history.replaceState(null, "", "#" + name); } catch (err) { location.hash = name; }
  });

  window.addEventListener("hashchange", function () {
    showPage(location.hash.replace("#", ""));
  });

  // Mobile menu button
  navButton.addEventListener("click", function () {
    var open = navMenu.classList.toggle("show");
    navButton.setAttribute("aria-expanded", open ? "true" : "false");
  });

  // Project filter buttons
  document.getElementById("filters").addEventListener("click", function (e) {
    var button = e.target.closest(".filter");
    if (!button) return;
    var chosen = button.getAttribute("data-filter");

    document.querySelectorAll(".filter").forEach(function (b) {
      b.classList.toggle("active", b === button);
    });
    document.querySelectorAll(".pcard").forEach(function (card) {
      card.hidden = !(chosen === "All" || card.getAttribute("data-category") === chosen);
    });
  });


  /* ===================================================================
     5. EXTRAS
     =================================================================== */

  // Greeting on the Home page ("Good morning, I'm ...")
  function setGreeting() {
    var hour = new Date().getHours();
    var word = hour < 12 ? "Good morning" : hour < 18 ? "Good afternoon" : "Good evening";
    document.getElementById("greet").textContent = word + ", I'm";
  }

  // Live clock on the Contact page (your local time)
  function startClock() {
    var clock = document.getElementById("clock");
    var format;
    try {
      format = new Intl.DateTimeFormat("en-US", { weekday: "short", hour: "numeric", minute: "2-digit", timeZone: S.timezoneId });
    } catch (err) { return; }
    function tick() { clock.textContent = format.format(new Date()); }
    tick();
    setInterval(tick, 20000);
  }

  // "Copy email" and "Copy number" buttons
  document.addEventListener("click", function (e) {
    var button = e.target.closest("[data-copy]");
    if (!button) return;

    var source = document.getElementById(button.getAttribute("data-copy"));
    var label = button.querySelector(".lbl");
    var original = label.textContent;

    function flash(message, ms) {
      label.textContent = message;
      setTimeout(function () { label.textContent = original; }, ms);
    }
    function selectText() {                     // fallback when copying is blocked
      var range = document.createRange();
      range.selectNodeContents(source);
      var selection = window.getSelection();
      selection.removeAllRanges();
      selection.addRange(range);
      flash("Selected, press copy", 2500);
    }

    try {
      navigator.clipboard.writeText(source.textContent.trim()).then(function () { flash("Copied", 1800); }, selectText);
    } catch (err) {
      selectText();
    }
  });


  /* ===================================================================
     START: build everything, then show the page from the web address
     =================================================================== */
  document.title = S.siteTitle;
  var meta = document.querySelector('meta[name="description"]');
  if (!meta) {
    meta = document.createElement("meta");
    meta.name = "description";
    document.head.appendChild(meta);
  }
  meta.content = S.siteDescription;

  buildHome();
  buildAbout();
  buildProjects();
  buildResume();
  buildContact();
  fillTexts();

  document.getElementById("year").textContent = new Date().getFullYear();
  setGreeting();
  startClock();

  loadProfilePicture();
  loadCovers();
  loadProjectPictures();

  showPage(location.hash.replace("#", ""), false);
})();
